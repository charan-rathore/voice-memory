import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const pg = await browser.newPage({ viewport: { width: 1280, height: 900 } });
await pg.goto('http://127.0.0.1:8322/', { waitUntil: 'networkidle' });
await pg.fill('#q', 'What was the creatinine value and unit in the September report?');
await pg.locator('#askbar').evaluate(f => f.requestSubmit());
await pg.waitForSelector('#answer .verdict-chip', { timeout: 45000 });
await pg.waitForTimeout(1800);
await pg.locator('#answer').screenshot({ path: '/tmp/chip-value-v2.png' });
console.log(await pg.evaluate(() => [...document.querySelectorAll('#answer .dd-tile span')].map(e => e.textContent).join(' | ')));
await browser.close();
