// Writes site/snapshot.js (+ snapshot-visuals.js): answers the landing page can show for its suggested
// questions while the free host wakes up. Every entry is produced by the real
// engine through the public API, never written by hand.
//   node scripts/build-snapshot.mjs
import { writeFileSync } from "node:fs";
import { createLocalServer } from "../src/server.mjs";

const srv = createLocalServer({ port: 0 });
await new Promise((r) => srv.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${srv.address().port}/api/public`;
await srv.loadPublicCases();
const get = async (p) => (await fetch(base + p)).json();
const { cases } = await get("/cases");
const EXTRA = {
  health: ["What is the TSH?", "What was the preliminary ferritin?"],
  deal: ["Is there a signed contract?", "What is the deadline?"],
};
const answers = {};
for (const c of cases)
  for (const q of [...c.suggestions, ...(EXTRA[c.id] ?? [])]) {
    const r = await fetch(base + "/ask", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ case: c.id, question: q }),
    });
    // Saved answers keep the sentence and citations; the chart and trace
    // come from the live engine.
    const { visual, semantic, ...rest } = await r.json();
    void visual;
    void semantic;
    answers[`${c.id}|${q}`] = rest;
  }
const docs = {};
for (const d of cases.find((c) => c.id === "deal").documents)
  docs[d.title] = (await get(`/doc/deal/${d.id}`)).document.text;
const graphs = {
  health: await get("/graph/health"),
  deal: await get("/graph/deal"),
};
// Visual summaries in each narration language, so the answer panel's
// picture is there before the free host wakes.
// The picture is the same in every language; only the narration differs.
const visuals = {};
for (const c of cases)
  for (const lang of ["en", "hi", "hinglish"]) {
    const { visual } = await get(`/visual/${c.id}?lang=${lang}`);
    if (!visual) continue;
    const v = (visuals[c.id] ??= { visual: null, narration: {} });
    // The overview draws strips, not history: keep the snapshot lean.
    if (lang === "en")
      v.visual = JSON.parse(
        JSON.stringify(visual, (k, x) =>
          k === "history" || k === "printedRange" ? undefined : x,
        ),
      );
    v.narration[lang] = visual.narration ?? null;
  }
const strip = (c) => ({
  ...c,
  documents: c.documents.map(({ title, filename, kind, pages }) => ({
    title,
    filename,
    kind,
    pages,
  })),
});
writeFileSync(
  new URL("../site/snapshot.js", import.meta.url),
  "// Generated by scripts/build-snapshot.mjs from the real engine. Do not edit.\nwindow.VM_SNAPSHOT = " +
    JSON.stringify({
      generatedAt: new Date().toISOString().slice(0, 10),
      cases: cases.map(strip),
      answers,
      docs,
      graphs,
    }) +
    ";\n",
);
// Narrated overviews load with the lazy visual chunk, not the first load.
writeFileSync(
  new URL("../site/snapshot-visuals.js", import.meta.url),
  "// Generated by scripts/build-snapshot.mjs from the real engine. Do not edit.\nwindow.VM_SNAPSHOT_VISUALS = " +
    JSON.stringify(visuals) +
    ";\n",
);
console.log("snapshot:", Object.keys(answers).length, "answers");
srv.close();
process.exit(0);
