// Writes site/snapshot.js: answers the landing page can show for its suggested
// questions while the free host wakes up. Every entry is produced by the real
// engine through the public API, never written by hand.
//   node scripts/build-snapshot.mjs
import { writeFileSync } from "node:fs";
import { createLocalServer } from "../src/server.mjs";

const srv = createLocalServer({ port: 0 });
await new Promise((r) => srv.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${srv.address().port}/api/public`;
await srv.loadPublicCases();
const get = async (p) => (await fetch(base + p)).json();
const { cases } = await get("/cases");
const EXTRA = {
  health: ["What is the TSH?", "What was the preliminary ferritin?"],
  deal: ["Is there a signed contract?", "What is the deadline?"],
};
const answers = {};
for (const c of cases)
  for (const q of [...c.suggestions, ...(EXTRA[c.id] ?? [])]) {
    const r = await fetch(base + "/ask", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ case: c.id, question: q }),
    });
    answers[`${c.id}|${q}`] = await r.json();
  }
const docs = {};
for (const d of cases.find((c) => c.id === "deal").documents)
  docs[d.title] = (await get(`/doc/deal/${d.id}`)).document.text;
const graphs = {
  health: await get("/graph/health"),
  deal: await get("/graph/deal"),
};
const strip = (c) => ({
  ...c,
  documents: c.documents.map(({ title, filename, kind, pages }) => ({
    title,
    filename,
    kind,
    pages,
  })),
});
writeFileSync(
  new URL("../site/snapshot.js", import.meta.url),
  "// Generated by scripts/build-snapshot.mjs from the real engine. Do not edit.\nwindow.VM_SNAPSHOT = " +
    JSON.stringify({
      generatedAt: new Date().toISOString().slice(0, 10),
      cases: cases.map(strip),
      answers,
      docs,
      graphs,
    }) +
    ";\n",
);
console.log("snapshot:", Object.keys(answers).length, "answers");
srv.close();
process.exit(0);
